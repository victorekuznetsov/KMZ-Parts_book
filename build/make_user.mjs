/* Manage catalog logins (writes auth/accounts.mjs). Node ESM, no deps.

   Usage:
     node build/make_user.mjs set <login> <password> [--name "Имя"] \
          [--role permanent|temporary] [--expires YYYY-MM-DD]
     node build/make_user.mjs del  <login>
     node build/make_user.mjs list
     node build/make_user.mjs secret        # print a fresh AUTH_SECRET for Vercel

   Permanent logins never expire. Temporary logins require --expires and stop
   working after that date (checked at login on the server).
*/
import { hashPassword, b64urlEncode, randomBytes } from "../auth/token.mjs";
import fs from "fs";
import path from "path";
import { fileURLToPath, pathToFileURL } from "url";

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const FILE = path.join(ROOT, "auth", "accounts.mjs");

async function loadUsers() {
  if (!fs.existsSync(FILE)) return [];
  const mod = await import(pathToFileURL(FILE).href + "?t=" + Date.now());
  return (mod.default && mod.default.users) || [];
}
function saveUsers(users) {
  const body = "/* Catalog logins — generated by build/make_user.mjs. Password hashes are\n" +
    "   PBKDF2-SHA256 (safe to commit). Never commit AUTH_SECRET — set it in Vercel. */\n" +
    "export default " + JSON.stringify({ users }, null, 2) + ";\n";
  fs.writeFileSync(FILE, body);
}
function arg(flag, def) {
  const i = process.argv.indexOf(flag);
  return i >= 0 && process.argv[i + 1] ? process.argv[i + 1] : def;
}

const cmd = process.argv[2];
const users = await loadUsers();

if (cmd === "secret") {
  console.log(b64urlEncode(randomBytes(32)));
  console.log("→ Добавьте в Vercel: Settings → Environment Variables → AUTH_SECRET = <это значение>");
} else if (cmd === "list") {
  if (!users.length) console.log("(нет учёток)");
  users.forEach(u => console.log(
    (u.role === "permanent" ? "♾  " : "⏳ ") + u.u.padEnd(16) +
    (u.name ? " — " + u.name : "") +
    (u.role === "temporary" ? "  до " + u.expires : "")));
} else if (cmd === "del") {
  const login = process.argv[3];
  const next = users.filter(u => u.u !== login);
  saveUsers(next);
  console.log(next.length < users.length ? "Удалён: " + login : "Не найдено: " + login);
} else if (cmd === "set") {
  const login = process.argv[3], password = process.argv[4];
  if (!login || !password) { console.error("Нужно: set <login> <password> [--role ...] [--expires ...] [--name ...]"); process.exit(1); }
  const role = arg("--role", "temporary");
  const expires = arg("--expires", null);
  const name = arg("--name", "");
  if (role === "temporary" && !expires) { console.error("Для временного логина укажите --expires YYYY-MM-DD"); process.exit(1); }
  if (expires && isNaN(new Date(expires + "T23:59:59").getTime())) { console.error("Неверная дата --expires (нужно YYYY-MM-DD)"); process.exit(1); }
  const rec = await hashPassword(password);
  const entry = { u: login, name, role, expires: role === "permanent" ? null : expires, ...rec };
  const idx = users.findIndex(u => u.u === login);
  if (idx >= 0) users[idx] = entry; else users.push(entry);
  saveUsers(users);
  console.log((idx >= 0 ? "Обновлён" : "Создан") + " " + role + " логин: " + login +
    (entry.expires ? " (до " + entry.expires + ")" : ""));
} else {
  console.log("Команды: set | del | list | secret  (см. шапку файла)");
}
